"""Independent consultation and deterministic quote selection for report review."""

import json
import re

from pydantic import Field, field_validator

from .schemas import (
    CaseProfile,
    Fact,
    Candidate,
    ChoiceLetter,
    EvidenceID,
    Report,
    Review,
    ReviewIssue,
    StrictModel,
)
from .quality import report_texts


class BlindOpinion(StrictModel):
    answer_choice: ChoiceLetter | None = None
    candidates: list[Candidate] = Field(default_factory=list, max_length=3)
    limitations: list[str] = Field(default_factory=list, max_length=3)

    @field_validator("candidates")
    @classmethod
    def reject_template_copy(cls, candidates):
        for candidate in candidates:
            if candidate.name == "独立候选疾病" or any(
                claim.text == "患者自身的支持依据" for claim in candidate.support
            ):
                raise ValueError(
                    "独立判断仍包含结构示例占位文字，必须填写真实候选及患者依据"
                )
        return candidates


class BlindChoiceOpinion(BlindOpinion):
    answer_choice: ChoiceLetter


class IndexedIssue(StrictModel):
    report_id: EvidenceID
    source_id: EvidenceID
    reason: str = Field(min_length=1, max_length=400)


class IndexedReview(StrictModel):
    issues: list[IndexedIssue] = Field(max_length=4)


class SelectedFact(StrictModel):
    name: str = Field(min_length=1, max_length=70)
    source_id: EvidenceID


class SelectedCaseProfile(StrictModel):
    facts: list[SelectedFact] = Field(default_factory=list, max_length=16)


def resolve_facts(selection, source_rows):
    sources = {r["id"]: r for r in source_rows if r["kind"] == "case"}
    facts, notes = [], []
    for item in selection.facts:
        source = sources.get(item.source_id)
        if not source:
            notes.append(item.name + "：未选择有效病例原文片段")
            continue
        quote = source["text"].strip()
        facts.append(
            Fact(
                name=item.name,
                value=quote,
                source_id=source["evidence_id"],
                source_quote=quote,
                source_span={
                    "id": source["id"],
                    "start": source["start"],
                    "end": source["end"],
                },
            )
        )
    return CaseProfile(facts=facts), notes


def source_index(evidence):
    """Record exact character spans. Failed tools and pixel placeholders are excluded."""
    rows = []
    for item in evidence:
        if item.status != "completed" or item.id == "I-original":
            continue
        # Sentence boundaries preserve decimal values and abbreviations. Quotes are
        # sliced from the snapshot, never translated or regenerated by a model.
        for number, match in enumerate(
            re.finditer(r"[^\n]+?(?:[。！？]|(?<=[.!?])\s+|$|\n)", item.content), 1
        ):
            start, end = match.span()
            text = item.content[start:end]
            if text.strip():
                for offset in range(start, end, 200):
                    chunk_end = min(offset + 200, end)
                    rows.append(
                        {
                            "id": f"{item.id}-S{number}-{(offset - start) // 200 + 1}",
                            "evidence_id": item.id,
                            "start": offset,
                            "end": chunk_end,
                            "text": item.content[offset:chunk_end],
                            "kind": item.kind,
                            "source_type": item.source_type,
                        }
                    )
    return rows


def report_index(report: Report):
    texts = report_texts(report)
    return [{"id": f"R-{i + 1}", "text": text} for i, text in enumerate(texts)]


def resolve_review(review, report_rows, source_rows):
    reports = {row["id"]: row for row in report_rows}
    sources = {row["id"]: row for row in source_rows}
    issues, spans, notes = [], [], []
    for issue in review.issues:
        report = reports.get(issue.report_id)
        source = sources.get(issue.source_id)
        if not report or not source:
            notes.append("复核意见引用不存在的报告字段或来源片段")
            continue
        issues.append(
            ReviewIssue(
                report_quote=report["text"],
                source_quote=source["text"],
                reason=issue.reason,
                source_type=source["source_type"],
                evidence_ids=[source["evidence_id"]],
            )
        )
        spans.append(
            {
                "report_id": issue.report_id,
                "source_id": issue.source_id,
                "evidence_id": source["evidence_id"],
                "start": source["start"],
                "end": source["end"],
            }
        )
    return Review(issues=issues), spans, notes


def blind_prompt(state):
    # Deliberately exclude plan, retrieved sources, observer opinions, clinical
    # contrast and draft report: all are influenced by the primary model.
    cases = [
        e.model_dump()
        for e in state["evidence"]
        if e.kind == "case" and e.status == "completed"
    ]
    return (
        "独立分析病例和原始胸片，未提供其他模型的判断。提出至多三个具体候选，"
        "每项给出患者证据与反证，引用真实C编号；直接观察原图可引用I-original。"
        "证据不足时明确限制，不编造阴性或检查。问题和选项只定义任务，不是患者事实。"
        "按问题要求判断诊断、分期或严重程度；选择题填写对应字母，其他任务填null。"
        + (
            "附图已作为图像输入提供，请独立观察；视觉依据引用I-original，无需C编号证明影像表现。"
            if state["case"].get("image_path")
            else "本次没有图像输入，不得声称已观察影像。"
        )
        + "\n问题："
        + state.get("question", "")
        + "\n原始病例："
        + json.dumps(cases, ensure_ascii=False)
    )
